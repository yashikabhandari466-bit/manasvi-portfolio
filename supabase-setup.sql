-- Run this SQL in Supabase Dashboard > SQL Editor.
-- Create a PUBLIC bucket for portfolio images. Public means anyone can view images;
-- only authenticated users can upload/delete through the policies below.

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('portfolio-media', 'portfolio-media', true, 10485760,
        array['image/jpeg','image/png','image/webp','image/gif'])
on conflict (id) do update set
  public = true,
  file_size_limit = 10485760,
  allowed_mime_types = array['image/jpeg','image/png','image/webp','image/gif'];

create table if not exists public.portfolio_media (
  id bigint generated by default as identity primary key,
  title text not null,
  category text not null default 'Journalism',
  storage_path text not null unique,
  public_url text not null,
  user_id uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

alter table public.portfolio_media enable row level security;

drop policy if exists "Public can view portfolio media records" on public.portfolio_media;
create policy "Public can view portfolio media records"
on public.portfolio_media for select using (true);

drop policy if exists "Authenticated user can add own media records" on public.portfolio_media;
create policy "Authenticated user can add own media records"
on public.portfolio_media for insert to authenticated
with check (auth.uid() = user_id);

drop policy if exists "Authenticated user can delete own media records" on public.portfolio_media;
create policy "Authenticated user can delete own media records"
on public.portfolio_media for delete to authenticated
using (auth.uid() = user_id);

drop policy if exists "Public can view portfolio images" on storage.objects;
create policy "Public can view portfolio images"
on storage.objects for select using (bucket_id = 'portfolio-media');

drop policy if exists "Authenticated user can upload portfolio images" on storage.objects;
create policy "Authenticated user can upload portfolio images"
on storage.objects for insert to authenticated
with check (
  bucket_id = 'portfolio-media'
  and (storage.foldername(name))[1] = auth.uid()::text
);

drop policy if exists "Authenticated user can delete own portfolio images" on storage.objects;
create policy "Authenticated user can delete own portfolio images"
on storage.objects for delete to authenticated
using (
  bucket_id = 'portfolio-media'
  and (storage.foldername(name))[1] = auth.uid()::text
);
